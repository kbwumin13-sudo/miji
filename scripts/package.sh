#!/bin/bash
set -euo pipefail
project_dir="$(cd "$(dirname "$0")/.." && pwd)"
cd "$project_dir"
configuration="${1:-release}"
build_dir="${MIJI_BUILD_DIR:-$project_dir/.build}"
swift build --scratch-path "$build_dir" -c "$configuration"
binary_dir="$(swift build --scratch-path "$build_dir" -c "$configuration" --show-bin-path)"
output_dir="${MIJI_OUTPUT_DIR:-$project_dir/output}"
app_path="$output_dir/觅迹.app"
mkdir -p "$app_path/Contents/MacOS" "$app_path/Contents/Resources"
cp "$binary_dir/Miji" "$app_path/Contents/MacOS/Miji"
cp "$binary_dir/miji-cli" "$app_path/Contents/MacOS/miji-extract"
cp resources/Info.plist "$app_path/Contents/Info.plist"
mkdir -p "$app_path/Contents/Resources/Licenses"
cp Vendor/OilFind/LICENSE "$app_path/Contents/Resources/Licenses/OilFind-MIT.txt"
icon_dir="$(mktemp -d "${TMPDIR:-/tmp}/miji-icon.XXXXXX")"
trap 'rm -rf "$icon_dir"' EXIT
swift scripts/make-icon.swift "$icon_dir/AppIcon.iconset"
iconutil -c icns "$icon_dir/AppIcon.iconset" -o "$app_path/Contents/Resources/AppIcon.icns"
codesign --force --sign - --identifier com.haiyu.miji.extract "$app_path/Contents/MacOS/miji-extract"
codesign --force --sign - --identifier com.haiyu.miji "$app_path"
codesign --verify --deep --strict "$app_path"
version="$(/usr/libexec/PlistBuddy -c 'Print :CFBundleShortVersionString' resources/Info.plist)"
archive_name="Miji-$version-macOS-arm64.zip"
ditto -c -k --sequesterRsrc --keepParent "$app_path" "$output_dir/$archive_name"
(cd "$output_dir" && shasum -a 256 "$archive_name" > "$archive_name.sha256")
printf '%s\n' "$app_path"
