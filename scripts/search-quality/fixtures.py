#!/usr/bin/env python3
"""Create fictional task corpus. No user data. Labels frozen before algorithm changes."""
import argparse, json, pathlib, zipfile, html
p=argparse.ArgumentParser();p.add_argument('directory',type=pathlib.Path);p.add_argument('--competitors',type=int,default=720);a=p.parse_args()
out=a.directory;out.mkdir(parents=True,exist_ok=True)
docs=[];queries=[]
def add(path,text,root='desk',kind='document',family=None):
    d=dict(path=path,text=text,root=root,kind=kind,modified=1700000000.0,labels=[],family=family or root+'/'+path)
    docs.append(d);return root+'/'+path
cores=[('潮汐储能','潮汐储能：电池容量与负荷调度设计。给出逐小时功率约束、容量选型和验证方法。'),('海棠灌溉','海棠灌溉：土壤湿度阈值与节水试验。给出传感器标定、灌溉周期和对照结论。'),('光谱校准','光谱校准：暗电流扣除、波长拟合与误差分析的完整操作步骤。'),('极地航线','极地航线：海冰观测与航路风险。对比三条路线的窗口与补给条件。'),('雾港预算','雾港预算：公共设施改造的成本表、资金来源和审核意见。'),('nebula cache','nebula cache design: eviction policy, bounded memory and invalidation tests.'),('矩阵分解','矩阵分解：QR 与奇异值分解的算法推导、数值稳定性与习题。'),('Café 模型','Café 模型：中文 English 混合资料的参数说明与独立实验。')]
targets=[]
for i,(q,body) in enumerate(cores):
    ext = {2:'docx',5:'pdf'}.get(i,'txt')
    target=add(f'资料/record-{i+1:02d}.{ext}',body);targets.append(target)
    queries.append(dict(id=f'q{i+1:02}',query=q,intent='找到解释该主题方法的核心资料',scope='content',targets=[target],holdout=i in (3,7),task='single'))
# Multi-resource tasks and versions, same-body copies belong to one family.
support=add('资料/support-01.txt','潮汐储能：补充实验记录，容量边界条件与温度影响。')
copy=add('副本/record-01.txt',cores[0][1],family=targets[0])
version=add('资料/version-02.txt','潮汐储能第二版：容量模型、损耗修正与负荷调度。')
longtarget=add('资料/monograph.txt','光谱校准：完整实验手册\n'+('\n仪器设置、标定曲线与误差来源说明。'*450)+'\n光谱校准的复核表与计算结果。')
offline=add('档案/record-01.txt',cores[1][1],root='offline')
mixed=add('资料/海棠-方案.txt','土壤湿度阈值与灌溉周期的完整设计。')
phrase=add('资料/exact.txt','alpha beta calibration manual: step-by-step error correction.')
near=add('资料/near.txt','alpha scattered notes '+('unrelated filler '*90)+' beta appears in an appendix.')
blocked=add('资料/blocked.txt','alpha beta calibration obsolete blocked version.')
ocr=add('收据/图像样本.png','图片文字检索 海棠春风 简体中文 搜索内容 Total 合计 128.00',kind='image')
name=add('课程/数学分析.pdf','极限与连续函数，级数。')
app=add('应用/StarNote.app','',kind='application')
for i in range(60): add(f'名称/旧稿-潮汐储能-{i:03}.txt','只包含占位符，不涉及设计内容。')
# All competitors contain the phrases, mostly as incidental appended references.
for i in range(a.competitors):
    body=f'运行日志 {i:04d}：本文件主题为打印机巡检。\n'+('状态正常；耗材检查；网络探测；\n'*70)+'附录：'+ '；'.join(q for q,_ in cores)+f'；alpha beta；海棠春风；记录编号 {i:04d}。'
    add(f'日志/log-{i:04d}.txt',body)
extra=[
('潮汐 储能','content',[targets[0],support,version],'multi',False,{}),
('潮汐储能','all',[targets[0]],'single',False,{}),
('海棠 湿度','all',[mixed,targets[1]],'multi',False,{}),
('"alpha beta" -blocked','content',[phrase],'single',False,{}),
('光谱校准 path:资料','content',[targets[2],longtarget],'multi',True,{}),
('海棠春风 kind:图片','content',[ocr],'single',True,{}),
('海棠灌溉','content',[offline,targets[1]],'multi',False,{}),
('海棠灌溉','content',[targets[1]],'single',False,{'onlineOnly':True}),
('矩阵分解 ext:txt','content',[targets[6]],'single',False,{}),
('nebula eviction','content',[targets[5]],'single',True,{}),
('cafe\u0301 模型','content',[targets[7]],'single',False,{}),
('数学分析','name',[name],'single',False,{}),
('sxfx','all',[name],'single',True,{}),
('shuxue','name',[name],'single',False,{}),
('Star','all',[app],'single',False,{}),
('"alpha beta" path:资料 -path:日志','content',[phrase,blocked],'multi',False,{})]
for i,(q,scope,ts,task,holdout,filters) in enumerate(extra,9):
    queries.append(dict(id=f'q{i:02}',query=q,intent='按查询与范围找到指定资料',scope=scope,targets=ts,holdout=holdout,task=task,filters=filters))
for q in queries:
    # Exhaustive explicit labels: no unseen result silently treated as irrelevant.
    weak_logs = q['id'] in {f'q{i:02}' for i in list(range(1,11))+[12,15,16,17,19]}
    q['labels']={d['root']+'/'+d['path']: (3 if d['root']+'/'+d['path'] in q['targets'] or d['family'] in q['targets'] else 1 if weak_logs and d['path'].startswith('日志/') else 0) for d in docs}
    if q['query'].startswith('潮汐'):
        for t in [targets[0],support,version]:q['labels'][t]=3 if t==targets[0] else 2
        q['labels'][copy]=3
    q['annotation']='agent provisional; no user-confirmed labels'
    q.setdefault('filters',{})
# Physical plain text/Office data for preview; PNG/PDF also generated by qa-fixtures.swift.
for d in docs:
    dest=out/d['root']/d['path'];dest.parent.mkdir(parents=True,exist_ok=True)
    if dest.suffix == '.txt': dest.write_text(d['text'])
    if dest.suffix == '.docx':
        with zipfile.ZipFile(dest,'w') as z:
            z.writestr('[Content_Types].xml','<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/></Types>')
            z.writestr('_rels/.rels','<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/></Relationships>')
            z.writestr('word/document.xml','<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body><w:p><w:r><w:t>'+html.escape(d['text'])+'</w:t></w:r></w:p></w:body></w:document>')
# Minimal valid ASCII PDF for filename/pinyin tasks.
pdf=out/'desk/课程/数学分析.pdf';pdf.parent.mkdir(parents=True,exist_ok=True)
objects=[b'<< /Type /Catalog /Pages 2 0 R >>',b'<< /Type /Pages /Kids [3 0 R] /Count 1 >>',b'<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>',b'<< /Length 57 >>\nstream\nBT /F1 18 Tf 72 720 Td (Synthetic calculus notes) Tj ET\nendstream',b'<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>']
b=bytearray(b'%PDF-1.4\n');offsets=[0]
for i,o in enumerate(objects,1):offsets.append(len(b));b+=f'{i} 0 obj\n'.encode()+o+b'\nendobj\n'
x=len(b);b+=f'xref\n0 6\n0000000000 65535 f \n'.encode()+b''.join(f'{v:010d} 00000 n \n'.encode() for v in offsets[1:])+f'trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n{x}\n%%EOF\n'.encode();pdf.write_bytes(b)
(out/'manifest.json').write_text(json.dumps(dict(documents=docs),ensure_ascii=False,indent=2))
(out/'queries.json').write_text(json.dumps(dict(annotation='agent provisional',queries=queries,families={d['root']+'/'+d['path']:d['family'] for d in docs}),ensure_ascii=False,indent=2))
(out/'content-queries.txt').write_text('\n'.join(q['query'] for q in queries if q['scope']=='content'))
print(json.dumps(dict(directory=str(out),documents=len(docs),queries=len(queries),holdout=sum(q['holdout'] for q in queries))))
